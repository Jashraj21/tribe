  static NortheastDistrict? findByName(String name) {
    try {
      return allDistricts.firstWhere(
        (d) => d.name.toLowerCase() == name.toLowerCase() ||
               d.districtName.toLowerCase() == name.toLowerCase(),
      );
    } catch (_) {
      return null;
    }
  }
